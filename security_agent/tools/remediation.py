"""Fix generation and (gated) application.

Two tools, two very different risk levels:

- `propose_fix` only ever writes a reviewable file to reports/fixes/ --
  it never touches the target codebase/system, so it needs no approval
  at all, the same as writing the run report itself needs none. The
  patch/config-snippet content is authored by the model (as this tool's
  call arguments), not generated by a second LLM call inside the tool.
- `apply_fix_to_repo` actually changes a local git repo (new branch,
  applied patch, commit) -- a real write action. It always forces
  human approval under `any_write_to_target`, which (per
  guardrails.ALWAYS_REQUIRE_APPROVAL) cannot be disabled by editing
  scope.yaml. It never pushes to a remote or opens a PR itself --
  that step stays an explicit, separate human action.
"""
from __future__ import annotations

import re
import subprocess
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .. import config as cfg
from ..guardrails import Guardrails
from .base import Tool, ToolResult


def _slugify(text: str) -> str:
    text = re.sub(r"[^a-zA-Z0-9]+", "-", text.strip().lower())
    return text.strip("-")[:60] or "fix"


class ProposeFixTool(Tool):
    name = "propose_fix"
    description = (
        "Draft a concrete, reviewable fix for a confirmed finding: root "
        "cause, a patch (unified diff) or config/IaC snippet, and how to "
        "verify the fix works. Writes a file for human review -- does "
        "not touch the target, so no approval is needed. Call this for "
        "every finding with a known, demonstrable fix, right after "
        "reporting it."
    )
    action_category = "passive_recon"  # drafting only; nothing is touched
    parameters = {
        "type": "object",
        "properties": {
            "finding_title": {"type": "string", "description": "Short title matching the finding in the report."},
            "root_cause": {"type": "string", "description": "Why the vulnerability exists."},
            "patch": {
                "type": "string",
                "description": "A unified diff, or a config/IaC snippet, that fixes the root cause.",
            },
            "verification_steps": {
                "type": "string",
                "description": "Concrete steps to confirm the fix actually works (e.g. re-run which tool with what expected result).",
            },
            "target_file": {
                "type": "string",
                "description": "Optional: the file path the patch applies to, if known.",
            },
        },
        "required": ["finding_title", "root_cause", "patch", "verification_steps"],
    }

    def run(
        self,
        guardrails: Guardrails,
        finding_title: str,
        root_cause: str,
        patch: str,
        verification_steps: str,
        target_file: str | None = None,
        **_: Any,
    ) -> ToolResult:
        guardrails.authorize_local_action(
            self.name, finding_title, f"Draft fix for finding: {finding_title}"
        )

        fixes_dir = cfg.REPORTS_DIR / "fixes"
        fixes_dir.mkdir(parents=True, exist_ok=True)
        ts = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
        path = fixes_dir / f"{ts}-{_slugify(finding_title)}.md"

        content = (
            f"# Fix: {finding_title}\n\n"
            f"_Drafted {ts} UTC -- reviewable, not applied. Nothing on the "
            f"target has changed._\n\n"
            f"## Root cause\n\n{root_cause}\n\n"
            + (f"## Target file\n\n`{target_file}`\n\n" if target_file else "")
            + f"## Patch\n\n```diff\n{patch}\n```\n\n"
            f"## Verification\n\n{verification_steps}\n"
        )
        path.write_text(content, encoding="utf-8")

        guardrails.record_result(self.name, finding_title, f"Fix draft written to {path}")
        return ToolResult(ok=True, summary=f"Fix proposal written to {path}", data={"path": str(path)})


class ApplyFixToRepoTool(Tool):
    name = "apply_fix_to_repo"
    description = (
        "Apply an already-drafted fix (see propose_fix) to a LOCAL git "
        "repository: creates a new branch, applies the patch, and "
        "commits it. Never pushes to a remote and never opens a PR -- "
        "that stays a separate, explicit human action. Always requires "
        "human approval, unconditionally, regardless of scope.yaml."
    )
    action_category = "any_write_to_target"
    binary = "git"
    parameters = {
        "type": "object",
        "properties": {
            "repo_path": {"type": "string", "description": "Local path to the git repository."},
            "branch_name": {"type": "string", "description": "New branch name for the fix."},
            "patch_file": {"type": "string", "description": "Path to a unified-diff patch file (e.g. from propose_fix's output)."},
            "commit_message": {"type": "string", "description": "Commit message describing the fix."},
        },
        "required": ["repo_path", "branch_name", "patch_file", "commit_message"],
    }

    def run(
        self,
        guardrails: Guardrails,
        repo_path: str,
        branch_name: str,
        patch_file: str,
        commit_message: str,
        **_: Any,
    ) -> ToolResult:
        guardrails.authorize_write_action(
            self.name, repo_path,
            f"Apply fix patch {patch_file} to {repo_path} on new branch '{branch_name}'",
        )
        if not self.available():
            msg = "git is not installed on this runner."
            guardrails.record_refusal(self.name, repo_path, msg)
            return ToolResult(ok=False, summary=msg, data={})
        if not Path(repo_path).is_dir():
            msg = f"{repo_path} is not a local directory."
            guardrails.record_refusal(self.name, repo_path, msg)
            return ToolResult(ok=False, summary=msg, data={})

        steps = [
            ["git", "-C", repo_path, "checkout", "-b", branch_name],
            ["git", "-C", repo_path, "apply", patch_file],
            ["git", "-C", repo_path, "add", "-A"],
            ["git", "-C", repo_path, "commit", "-m", commit_message],
        ]
        log = []
        for step in steps:
            try:
                proc = subprocess.run(step, capture_output=True, text=True, timeout=60)
            except Exception as exc:  # noqa: BLE001
                guardrails.record_result(self.name, repo_path, f"error during {step}: {exc}")
                return ToolResult(ok=False, summary="\n".join(log) + f"\nerror: {exc}", data={})
            log.append(f"$ {' '.join(step)}\n{proc.stdout}{proc.stderr}")
            if proc.returncode != 0:
                guardrails.record_result(self.name, repo_path, "\n".join(log)[-500:])
                return ToolResult(ok=False, summary="\n".join(log), data={"failed_step": step})

        summary = "\n".join(log)
        guardrails.record_result(self.name, repo_path, summary[-500:])
        return ToolResult(ok=True, summary=summary, data={"branch": branch_name})
